"use strict";
const fs = require("fs");
const path = require("path");
const {spawnSync} = require("child_process");
const root = __dirname;
const backendPath = path.join(root, "computer-control", "backends", "macos-window-bounds.js");
const pluginPath = path.join(root, "computer-control", "desktop", "plugins", "macos-v75.js");
const loaderPath = path.join(root, "computer-control", "desktop", "index.js");
const facadePath = path.join(root, "computer-control", "index.js");
const backend = fs.readFileSync(backendPath, "utf8");
const plugin = fs.readFileSync(pluginPath, "utf8");
const loader = fs.readFileSync(loaderPath, "utf8");
const facade = fs.readFileSync(facadePath, "utf8");
let failed = false;
function check(label, ok) { console.log(`${label}: ${ok ? "PASS" : "FAIL"}`); if (!ok) failed = true; }
function syntax(file) { return spawnSync(process.execPath, ["--check", file]).status === 0; }
const scope = plugin.slice(plugin.indexOf("function maximizeWindow(application = {}, window = {})"), plugin.indexOf("module.exports ="));
check("required backend syntax", syntax(backendPath));
check("required plugin syntax", syntax(pluginPath));
check("required loader syntax", syntax(loaderPath));
check("required v74 helper integration", backend.includes("macos-window-bounds.swift"));
check("required bounds observation", backend.includes("function observeWindowBounds"));
check("required maximize mutation", backend.includes("function maximizeWindowBounds"));
check("required state-driven bounds verification", backend.includes("function waitForWindowBounds") && backend.includes("boundsEqual"));
check("required v72 composition", plugin.includes('require("./macos-v72")') && plugin.includes("...base"));
check("required maximize capability", plugin.includes('"window.maximize":"IMPLEMENTED"'));
check("required full descriptor", scope.includes("normalizeWindow(window)") && scope.includes("WINDOW_DESCRIPTOR_INSUFFICIENT"));
check("required application context", scope.includes("base.listWindows(application)"));
check("required fresh pre-action list", scope.includes("agentCtrl.listWindows()"));
check("required descriptor re-resolution", scope.includes("sameDescriptor(observedTarget, item)"));
check("required stale failure", scope.includes("WINDOW_TARGET_STALE"));
check("required ambiguous failure", scope.includes("WINDOW_TARGET_AMBIGUOUS"));
check("required handle diagnostics", scope.includes("observedHandle") && scope.includes("actionHandle") && scope.includes("handleRebound"));
check("required native maximize action", scope.includes("macosWindowBounds.maximizeWindowBounds(currentTarget)"));
check("required verified bounds postcondition", scope.includes("waitForWindowBounds(currentTarget, action.desired)"));
check("required verified MAXIMIZED success", scope.includes('state:"MAXIMIZED"') && scope.includes("maximized:true") && scope.includes("verified:true"));
check("required verification marker", scope.includes("native-ax-visible-frame-bounds"));
check("forbidden keyboard shortcut", !scope.includes("Cmd+") && !scope.includes("pressKeys"));
check("forbidden AppleScript", !scope.includes("osascript") && !scope.includes("System Events"));
check("required loader selects v75", loader.includes('darwin:"./plugins/macos-v75"'));
check("forbidden premature public facade", !facade.includes("function maximizeWindow("));
console.log(`verified-window-maximize-desktop-boundary=${failed ? "FAIL" : "PASS"}`);
process.exit(failed ? 1 : 0);
